#!/usr/bin/env python3
"""Resolve the outside law the library's documents cite; index it on the pointers.

Usage: python3 bin/extract_citations.py

Scans every extraction in text/ for citations to outside authority and checks
each against the catalog. Citations resolve at corpus level to the pointer
records in catalog/statute/ - A.C.A. to arkansas-code, U.S.C. to uscode-olrc,
C.F.R. to ecfr-api - unless a more specific record exists (a slug equal to, or
extending, the citation slug: ark-code-6-24-105-nepotism covers a cite to
6-24-105). Each pointer record indexes what resolves to it: this tool rewrites
the generated "## Resolved authorities" section of the record's own body
(authority -> citing documents), leaving the prose above the marker alone.
Anything that resolves to neither a record nor a pointer, including whatever
eyecite recognizes beyond the regexes (case law mostly), prints as UNRESOLVED
with its citing documents and fails the run - the signal to add a record or
pointer. eyecite is optional; without it the regex pass still runs.
"""

import re
import sys

from catalog import ROOT, records

MARKER = "## Resolved authorities"

ACA_RE = re.compile(r"\b(?:A\.C\.A\.?|Ark\.?\s*Code\s*Ann?\.?)\s*§+\s*(\d{1,2}-\d+-\d+)")
USC_RE = re.compile(r"\b(\d{1,2})\s*U\.?S\.?C\.?\s*§+\s*(\d+[a-z0-9]*)\b")
CFR_RE = re.compile(r"\b(\d{1,2})\s*C\.?F\.?R\.?\s*(?:§+\s*|[Pp]art\s+)?(\d+)(?:\.\d+)?\b")

try:
    from eyecite import get_citations
    from eyecite.models import FullCitation
except ImportError:
    get_citations = FullCitation = None


def main():
    recs = records()
    slugs = {r.slug for r in recs}
    by_slug = {r.slug: r for r in recs}

    def specific(slug):
        hits = sorted(s for s in slugs if s == slug or s.startswith(slug + "-"))
        return hits[0] if hits else None

    # label -> (candidate specific slug, pointer slug, citing stems)
    found = {}
    other = {}
    for path in sorted((ROOT / "text").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        for sec in ACA_RE.findall(text):
            key = (f"Ark. Code Ann. § {sec}", f"ark-code-{sec}", "arkansas-code")
            found.setdefault(key, set()).add(path.stem)
        for title, sec in USC_RE.findall(text):
            key = (f"{title} U.S.C. § {sec}", f"usc-{title}-{sec}", "uscode-olrc")
            found.setdefault(key, set()).add(path.stem)
        for title, part in CFR_RE.findall(text):
            key = (f"{title} CFR part {part}", f"cfr-{title}-{part}", "ecfr-api")
            found.setdefault(key, set()).add(path.stem)
        if get_citations:
            for cite in get_citations(text):
                matched = cite.matched_text()
                # full citations only: id./supra/short/unknown tokens are noise here,
                # and the regex passes own the statute reporters
                # "Ark. Code", not "Ark": the Ark. reporter (case law) must stay reportable
                if not isinstance(cite, FullCitation) or any(
                        m in matched for m in ("U.S.C", "USC", "C.F.R", "CFR",
                                               "A.C.A", "Ark. Code", "Ark Code")):
                    continue
                other.setdefault(matched, set()).add(path.stem)

    unresolved = 0
    tally = {}
    entries = {}  # pointer slug -> [(label, citers)] in sorted-label order
    for (label, slug, pointer), citers in sorted(found.items()):
        hit = specific(slug)
        if hit:
            print(f"RESOLVED {label} -> {hit} ({len(citers)} citing)")
        elif pointer in slugs:
            tally[pointer] = tally.get(pointer, 0) + 1
            entries.setdefault(pointer, []).append((label, citers))
        else:
            unresolved += 1
            print(f"UNRESOLVED {label} - no record, pointer {pointer} missing "
                  f"({len(citers)} citing: {', '.join(sorted(citers)[:5])})")

    for pointer, items in sorted(entries.items()):
        rec = by_slug[pointer]
        prose = rec.body.split("\n" + MARKER, 1)[0].rstrip()
        body = "\n".join(
            [prose, "", MARKER, "",
             "Generated by bin/extract_citations.py from the citations in the",
             "library's extractions - do not hand-edit this section.", ""] +
            [f"- {label} - cited by {len(citers)}: {', '.join(sorted(citers))}"
             for label, citers in items])
        if body == rec.body:
            continue
        rec.body = body
        rec.save()
        print(f"INDEXED {pointer} ({len(items)} authorities)")
    for rec in recs:
        # a pointer whose citations all vanished keeps a stale generated section
        if rec.slug in entries or MARKER not in rec.body:
            continue
        rec.body = rec.body.split("\n" + MARKER, 1)[0].rstrip()
        rec.save()
        print(f"CLEARED {rec.slug} (nothing resolves here any more)")
    for matched, citers in sorted(other.items()):
        unresolved += 1
        print(f"UNRESOLVED {matched} ({len(citers)} citing: {', '.join(sorted(citers)[:5])})")

    if not get_citations:
        print("NOTE eyecite not installed; regex pass only")
    covered = " · ".join(f"{n} -> {p}" for p, n in sorted(tally.items()))
    print(f"{len(found)} cited authorities ({covered}); {unresolved} UNRESOLVED")
    sys.exit(1 if unresolved else 0)


if __name__ == "__main__":
    main()
